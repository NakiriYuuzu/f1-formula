/** One tip for a random value in [0, 1). */
export function pickTip(rand: number = Math.random()): string {
  const n = LOADING_TIPS.length;
  const i = Number.isFinite(rand) ? Math.min(n - 1, Math.max(0, Math.floor(rand * n))) : 0;
  return LOADING_TIPS[i] ?? '';
}
